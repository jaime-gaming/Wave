import { describe, expect, it } from 'vitest';
import {
  autoClipStart,
  clipQuery,
  parseInvidiousResults,
  parsePipedResults,
  isArtistChannel,
  isAudioOnly,
  isAutoGenerated,
  isLyricVideo,
  isMusicVideo,
  pickClip,
  scoreClip,
  type ClipCandidate,
} from './clipSearch';

const song = { title: 'Midnight City', artist: 'M83', duration: 244 };
const candidate = (over: Partial<ClipCandidate> = {}): ClipCandidate => ({
  videoId: 'dX3k_QDnzHE',
  title: 'M83 - Midnight City (Official Video)',
  author: 'M83',
  duration: 244,
  ...over,
});

describe('clip search', () => {
  it('builds a compact query without duplicating the artist', () => {
    expect(clipQuery(song)).toBe('m83 midnight city');
    expect(clipQuery({ ...song, title: 'M83 Midnight City' })).toBe('m83 midnight city');
    expect(clipQuery({ ...song, artist: 'Unknown artist' })).toBe('midnight city');
  });

  it('prefers the upload whose length matches the song', () => {
    const wrongLength = candidate({
      videoId: 'aaaaaaaaaaa',
      title: 'M83 - Midnight City (Official Video)',
      duration: 1080,
    });
    expect(scoreClip(candidate(), song)).toBeGreaterThan(scoreClip(wrongLength, song));
    expect(pickClip([wrongLength, candidate()], song)?.videoId).toBe('dX3k_QDnzHE');
  });

  it('rejects covers, karaoke and reaction videos outright', () => {
    for (const title of [
      'Midnight City - M83 (Karaoke Version)',
      'Midnight City - M83 (Piano Cover)',
      'M83 Midnight City REACTION',
      'Midnight City (slowed + reverb)',
    ])
      expect(scoreClip(candidate({ title }), song)).toBe(0);
  });

  it('returns nothing when no candidate is convincing', () => {
    expect(pickClip([], song)).toBeNull();
    expect(
      pickClip([candidate({ title: 'Completely different song', author: 'Nobody' })], song),
    ).toBeNull();
    // A video id that is not eleven characters cannot be embedded.
    expect(pickClip([candidate({ videoId: 'short' })], song)).toBeNull();
  });

  it('works without a known song duration', () => {
    const unknown = { ...song, duration: 0 };
    expect(pickClip([candidate({ duration: 0 })], unknown)?.videoId).toBe('dX3k_QDnzHE');
  });

  it("only accepts the artist's own upload, never a stranger's repost", () => {
    const repost = candidate({ author: 'Some upload' });
    expect(isArtistChannel(repost, song)).toBe(false);
    expect(scoreClip(repost, song)).toBe(0);
    expect(pickClip([repost], song)).toBeNull();
    // The channel suffixes that really exist.
    for (const author of ['M83', 'M83VEVO', 'M83 Official', 'M83 - Topic', 'm83 music'])
      expect(isArtistChannel(candidate({ author }), song)).toBe(true);
    // A channel that merely mentions the song has nothing to do with the artist.
    expect(isArtistChannel(candidate({ author: 'Best of 2011' }), song)).toBe(false);
    // Multi-word artists keep working.
    expect(
      isArtistChannel(candidate({ author: 'The Midnight' }), {
        ...song,
        artist: 'The Midnight',
      }),
    ).toBe(true);
  });

  it('parses both provider shapes and skips unusable rows', () => {
    expect(
      parsePipedResults({
        items: [
          {
            url: '/watch?v=dX3k_QDnzHE',
            title: 'Midnight City',
            uploaderName: 'M83',
            duration: 244,
          },
          { url: '', title: 'Broken' },
          { url: '/watch?v=bad', title: 'Short id' },
        ],
      }),
    ).toEqual([{ videoId: 'dX3k_QDnzHE', title: 'Midnight City', author: 'M83', duration: 244 }]);
    expect(
      parseInvidiousResults([
        {
          type: 'video',
          videoId: 'dX3k_QDnzHE',
          title: 'Midnight City',
          author: 'M83',
          lengthSeconds: 244,
        },
        { type: 'playlist', playlistId: 'PL1234567890' },
        { type: 'video', videoId: 'nope', title: 'Nope' },
      ]),
    ).toEqual([{ videoId: 'dX3k_QDnzHE', title: 'Midnight City', author: 'M83', duration: 244 }]);
    expect(parsePipedResults(null)).toEqual([]);
    expect(parseInvidiousResults({})).toEqual([]);
  });
});

describe('autoClipStart', () => {
  it('splits the extra length of the upload, keeping the larger part at the start', () => {
    // A 30 s title card on a 240 s song: start 18 s in, which is where the music is.
    expect(autoClipStart(270, 240)).toBe(18);
    // Anything within two seconds is noise, not an intro.
    expect(autoClipStart(242, 240)).toBe(0);
    expect(autoClipStart(240, 240)).toBe(0);
  });

  it('never guesses wildly or divides by zero', () => {
    expect(autoClipStart(3_600, 60)).toBe(60);
    expect(autoClipStart(0, 240)).toBe(0);
    expect(autoClipStart(240, 0)).toBe(0);
    expect(autoClipStart(Number.NaN, 240)).toBe(0);
    // A short clip inside a long song is not a start problem.
    expect(autoClipStart(200, 400)).toBe(0);
  });
});

describe('a clip is a video, not the song with a still picture', () => {
  const official = candidate();
  // The label's own upload: the sleeve, held still, for the length of the record.
  const artTrack = candidate({
    videoId: 'bbbbbbbbbbb',
    title: 'M83 - Midnight City',
    author: 'M83 - Topic',
    duration: 244,
  });
  const audio = candidate({
    videoId: 'ccccccccccc',
    title: 'M83 - Midnight City (Official Audio)',
    author: 'M83',
    duration: 244,
  });

  it('never picks the auto-generated art track', () => {
    expect(isAutoGenerated(artTrack)).toBe(true);
    expect(scoreClip(artTrack, song)).toBe(0);
    expect(pickClip([artTrack], song)).toBeNull();
    expect(pickClip([artTrack, official], song)?.videoId).toBe(official.videoId);
  });

  it('puts the music video above the official audio of the same song', () => {
    expect(isMusicVideo(official)).toBe(true);
    expect(isAudioOnly(audio)).toBe(true);
    expect(scoreClip(official, song)).toBeGreaterThan(scoreClip(audio, song));
    expect(pickClip([audio, official], song)?.videoId).toBe(official.videoId);
  });

  it('still accepts the audio upload when it is the only thing there is', () => {
    // Nothing better exists: a muted sleeve beats no picture at all.
    expect(pickClip([audio], song)?.videoId).toBe(audio.videoId);
  });

  it('never shows a lyric video, even when it is all there is', () => {
    const lyric = candidate({
      videoId: 'eeeeeeeeeee',
      title: 'M83 - Midnight City (Lyric Video)',
      author: 'M83',
      duration: 244,
    });
    const plain = candidate({ videoId: 'fffffffffff', title: 'M83 - Midnight City (Lyrics)' });
    expect(isLyricVideo(lyric)).toBe(true);
    expect(isAudioOnly(lyric)).toBe(true);
    // Wave draws its own lyrics; a second set over a still frame is the one
    // thing worse than no picture.
    expect(scoreClip(lyric, song)).toBe(0);
    expect(pickClip([lyric], song)).toBeNull();
    expect(pickClip([plain], song)).toBeNull();
  });

  it('does not reject a title that only looks like it says "lyrics"', () => {
    // "Letters" is a word of its own, not the Spanish "letra" in a title.
    expect(isLyricVideo(candidate({ title: 'M83 - Midnight City (Letters Remix)' }))).toBe(false);
    expect(isLyricVideo(candidate({ title: 'M83 - Midnight City (Video Oficial)' }))).toBe(false);
  });

  it('does not treat a neutral title as a still picture', () => {
    const neutral = candidate({ title: 'M83 - Midnight City', author: 'M83' });
    expect(isAudioOnly(neutral)).toBe(false);
    expect(isMusicVideo(neutral)).toBe(false);
  });
});
